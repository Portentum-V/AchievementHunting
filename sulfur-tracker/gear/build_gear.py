"""Build gear-data.js for the SULFUR armor and trinket page from the installed game.

Armor goes in the head, torso, and two feet slots; trinkets go in the four
passive slots. Each item changes player stats while worn (its
modifiersOnEquipNew), and this script reads those the way the in-game
tooltip shows them, marking each line as a benefit or a drawback. It also
writes each modifier's raw value, so the page can total a full outfit the
way the game stacks them.
It exports icons to icons/ and writes window.SULFUR_GEAR for index.html.

    py -m pip install UnityPy dnfile
    py -I build_gear.py [path to the SULFUR install folder]
"""
import collections
import json
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))  # -I leaves the script folder off the path
from game_files import WIKI_SEARCH, Game, game_dir  # noqa: E402

OUT = HERE / "gear-data.js"
ICONS = HERE / "icons"

# The page's groups: the game's SlotType for each, and how many of it a
# player wears at once (EquipmentManager's slots: Head, Torso, LeftFoot and
# RightFoot, Passive0 to Passive3).
SLOTS = [("Head", "Head", 1), ("Torso", "Chest", 1), ("Feet", "Feet", 2), ("PassiveEnhancements", "Trinkets", 4)]

# Which way each player attribute helps: +1 when more is better (the
# default), -1 when less is better, 0 when it is neither.
DIRECTION = {"Stat_WeaponWeightPenalty": -1, "Stat_DefaultTimeScale": 0}

# The resistance each damage type checks (DamageType assets). The game
# multiplies that damage by (100 - resistance) / 100, so a point is 1% less.
RESISTS = {"Resistance_Armor": "normal and critical hits", "Resistance_Explosive": "explosions",
           "Resistance_Fire": "fire", "Resistance_Frost": "frost and water", "Resistance_Electric": "electric",
           "Resistance_Poison": "poison", "Resistance_Holy": "light", "Resistance_Shadow": "shadow and dark",
           "Resistance_Bleed": "bleed and sacrifice"}


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    game = Game(game_dir())
    E = game.enums
    ICONS.mkdir(exist_ok=True)
    slot_name = {s: name for s, name, _ in SLOTS}

    items, attrs = [], {}
    for i, t in game.items.items():
        slot = E["SlotType"].get(t.get("slotType"))
        if E["UseType"].get(t.get("useType")) != "Equippable" or slot not in slot_name:
            continue
        if t["deprecated"] or t["excludeFromDatabase"]:
            continue
        lines = game.equip_lines(t)
        for l in lines:
            if l["key"] not in attrs:
                a = game.entity_attrs.get(l["attribute"], {})
                d = -1 if a.get("isNegativeEffect") else DIRECTION.get(l["key"], 1)
                attrs[l["key"]] = {**game.entity_attr_info(l["attribute"]), "dir": d}
                if l["key"] in RESISTS:
                    attrs[l["key"]]["resists"] = RESISTS[l["key"]]
            l["kind"] = "side" if attrs[l["key"]]["dir"] == 0 else \
                "good" if (l["value"] >= 0) == (attrs[l["key"]]["dir"] > 0) else "bad"
        icon = game.save_icon(i, ICONS)
        armor = sum(l["value"] for l in lines if l["key"] == "Resistance_Armor" and l["modType"] == 100)
        items.append({
            "name": game.name(t), "key": t["m_Name"], "url": WIKI_SEARCH + game.name(t).replace(" ", "+"),
            "img": icon and "icons/" + icon, "quality": game.quality(t), "sell": game.sell(t), "grid": game.grid(t),
            "group": slot_name[slot], "armor": armor,
            # Trinkets do not wear out (InventoryItem.HasDurability leaves out passive slots).
            "durability": round(t["maxDurability"]) if slot != "PassiveEnhancements" else None,
            "effects": [{"text": l["text"], "kind": l["kind"]} for l in lines],
            "mods": [{"a": l["key"], "v": l["value"], "t": l["modType"]} for l in lines],
            "flavor": game.text(f"Items/{t['m_Name']}_flavor"),
        })

    data = {"source": "SULFUR game files", "version": game.version, "built": date.today().isoformat(),
            "groups": [{"name": name, "count": n} for _, name, n in SLOTS], "attrs": attrs,
            "items": sorted(items, key=lambda o: (o["name"].lower(), o["key"]))}
    OUT.write_text(
        "// Generated by build_gear.py from the installed SULFUR game files. Do not edit by hand.\n"
        "window.SULFUR_GEAR = " + json.dumps(data, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8")
    groups = collections.Counter(o["group"] for o in items)
    print(f"{len(items)} items -> {OUT.name}, icons -> {ICONS.name}/")
    print("groups:", dict(groups))
    print("no listed effect:", ", ".join(o["name"] for o in items if not o["effects"]) or "none")
    print("no icon:", ", ".join(o["name"] for o in items if not o["img"]) or "none")


if __name__ == "__main__":
    main()
