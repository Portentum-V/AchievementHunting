"""Build scrolls-data.js for the SULFUR scroll page from the installed game.

Scrolls are the elemental enchantments: drag one onto a weapon to enchant
it. The Scholar combines two scrolls into a stronger one; those are the
game's enchantment recipes. This script reads every scroll, its
description, and the weapon modifiers its enchantment applies, the way the
in-game tooltip shows them, plus the recipes that make and use it. It
exports icons to icons/ and writes window.SULFUR_SCROLLS for index.html.
Weapon oils are enchantments too, but not elemental, so they stay out.

    py -m pip install UnityPy dnfile
    py -I build_scrolls.py [path to the SULFUR install folder]
"""
import collections
import json
import re
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))  # -I leaves the script folder off the path
from game_files import WIKI_SEARCH, Game, game_dir  # noqa: E402

OUT = HERE / "scrolls-data.js"
ICONS = HERE / "icons"
ENCHANTMENT_RECIPE = 2  # RecipeData.Types.enchantment


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    game = Game(game_dir())
    E = game.enums

    ICONS.mkdir(exist_ok=True)
    scrolls = {}
    for i, t in game.items.items():
        if E["UseType"].get(t["useType"]) != "Enchantment" or t["deprecated"] or t["excludeFromDatabase"]:
            continue
        ench, effects = game.enchant_effects(t)
        if not (ench and ench["IsElemental"]) and not game.name(t).startswith("Scroll of"):
            continue
        # The description field holds lines that start with "- "; the
        # localization table overrides it when it has an entry. The in-game
        # tooltip shows only the effect lines, so both are kept whole.
        text = game.text(f"Items/{t['m_Name']}_description") or t["description"]
        desc = [re.sub(r"^[-\s]+", "", line).strip().rstrip('"').strip() for line in text.splitlines()]
        desc = [d for d in desc if d]
        icon = game.save_icon(i, ICONS)
        scrolls[i] = {
            "name": game.name(t), "url": WIKI_SEARCH + game.name(t).replace(" ", "+"),
            "img": icon and "icons/" + icon, "quality": game.quality(t), "sell": game.sell(t),
            "grid": game.grid(t), "desc": desc, "effects": effects,
            "flavor": game.text(f"Items/{t['m_Name']}_flavor"),
            "durability": ench["CostsDurability"] if ench else None,
            "from": [], "into": [],
        }

    rdb = next(o.read_typetree() for o in game.scripts("RecipeDatabase"))["recipes"]
    seen = set()
    for r in rdb:
        out = r["createsItem"]["value"]
        if r["type"] != ENCHANTMENT_RECIPE or out not in scrolls or not r["canBeCrafted"]:
            continue
        need = collections.Counter()
        for x in r["itemsNeeded"]:
            need[x["item"]["value"]] += x["quantity"]
        key = (out, tuple(sorted(need.items())))
        if key in seen:
            continue
        seen.add(key)
        ins = [{"n": game.name(game.items[k]), "q": q} for k, q in sorted(need.items(), key=lambda kv: game.name(game.items[kv[0]]))]
        scrolls[out]["from"].append(ins)
        for k in need:
            if k in scrolls and scrolls[out]["name"] not in scrolls[k]["into"]:
                scrolls[k]["into"].append(scrolls[out]["name"])
    for s in scrolls.values():
        s["into"].sort()
        s["tier"] = "Combined" if s["from"] else "Base"

    data = {"source": "SULFUR game files", "version": game.version, "built": date.today().isoformat(),
            "scrolls": sorted(scrolls.values(), key=lambda s: s["name"].lower())}
    OUT.write_text(
        "// Generated by build_scrolls.py from the installed SULFUR game files. Do not edit by hand.\n"
        "window.SULFUR_SCROLLS = " + json.dumps(data, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8")
    tiers = collections.Counter(s["tier"] for s in scrolls.values())
    print(f"{len(scrolls)} scrolls ({dict(tiers)}) -> {OUT.name}, icons -> {ICONS.name}/")
    print("no description:", ", ".join(s["name"] for s in scrolls.values() if not s["desc"]) or "none")
    print("no icon:", ", ".join(s["name"] for s in scrolls.values() if not s["img"]) or "none")


if __name__ == "__main__":
    main()
